// Writes src/phosphor.ts: the Phosphor icons the bar uses (Light weight, as the 21n apps use them), taken from
// @iconify-json/ph. The bar ships the path data inline, so it never loads an icon at run time.
// Run after changing ICONS or the @iconify-json/ph version: node scripts/phosphor-icons.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);
const set = require("@iconify-json/ph/icons.json");
const { version } = require("@iconify-json/ph/package.json");

/** The bar's icon name → the Phosphor icon it draws. */
const ICONS = {
  comment: "chat-circle-dots-light",
  inbox: "tray-light",
  drafts: "note-pencil-light",
  layers: "stack-light",
  close: "x-light",
  check: "check-light",
  reopen: "arrow-counter-clockwise-light",
  archive: "archive-light",
  trash: "trash-light",
  caret: "caret-down-light",
  help: "question-light",
};

const lines = Object.entries(ICONS).map(([name, id]) => {
  const icon = set.icons[id];
  if (!icon) throw new Error(`@iconify-json/ph has no ${id}`);
  const paths = [...icon.body.matchAll(/<path fill="currentColor" d="([^"]+)"\/>/g)].map((match) => match[1]);
  if (paths.length === 0 || paths.join("").length === 0) throw new Error(`${id} is not plain filled paths`);
  return `  /** ph:${id} */\n  ${name}: ${JSON.stringify(paths.join(""))},`;
});

writeFileSync(new URL("../src/phosphor.ts", import.meta.url), `// Generated by scripts/phosphor-icons.mjs from @iconify-json/ph ${version} (Phosphor Icons, MIT). Do not edit.

/** Phosphor icon path data, drawn filled in \`currentColor\` on a 256 x 256 view box. */
export const PHOSPHOR = {
${lines.join("\n")}
} as const;
`);
